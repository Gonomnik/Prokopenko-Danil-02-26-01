# Запрашиваем значение a с проверкой диапазона
f = True
while f:
    a = int(input("Введите a (0 <= a <= 50): "))
    if 0 <= a <= 50:
        f = False
    print("Ошибка! Введите число от 0 до 50.")

# Переменная для накопления суммы
total_sum = 0

# Функция range(a, 51) будет генерировать числа от a до 50 включительно
for i in range(a, 51):
    total_sum += i ** 2  # Возводим число в квадрат и прибавляем к сумме

print(f"Сумма квадратов чисел от {a} до 50 равна: {total_sum}")