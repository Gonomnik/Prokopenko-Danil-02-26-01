text = input("Введите строку: ")

# Считаем количество вхождений русской буквы 'а'
count_a = text.count('а')

# Заменяем букву 'а' на пустую строку (удаляем её)
new_text = text.replace('а', '')

print(f"Исходная строка: {text}")
print(f"Строка без букв 'а': {new_text}")
print(f"Удалено символов: {count_a}")