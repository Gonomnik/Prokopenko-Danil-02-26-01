N = int(input("Введите целое число N (> 1): "))

K = 0
power = 1  # 5 в степени 0 равно 1

# Пока 5 в степени K меньше или равно N, увеличиваем K
while power <= N:
    K += 1
    power *= 5  # Умножаем текущее значение на 5 (возводим в следующую степень)

print(f"Наименьшее целое число K, при котором 5^K > N: {K}")
print(f"(5^{K} = {power}, что больше {N})")